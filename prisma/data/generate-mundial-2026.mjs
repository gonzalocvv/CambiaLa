// ─── Generar stickers por equipo ────────────────────────────────────────────
function buildTeamStickers(team) {
  const result = [];
  // 1: Escudo (especial, isSpecial)
  result.push({
    number: `${team.code}1`,
    name: `Escudo ${team.code}`,
    team: team.code,
    rarity: 'especial',
    isSpecial: true,
  });
  // 2: Foto grupal
  result.push({
    number: `${team.code}2`,
    name: 'Foto del Equipo',
    team: team.code,
    rarity: 'comun',
    isSpecial: false,
  });
  // 3-17: jugadores
  team.players.forEach(([name, rarity], i) => {
    result.push({
      number: `${team.code}${i + 3}`,
      name,
      team: team.code,
      rarity,
      isSpecial: false,
    });
  });
  return result;
}

