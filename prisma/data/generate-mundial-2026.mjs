// ─── Generar stickers por equipo (20 c/u) ───────────────────────────────────
function buildTeamStickers(team) {
  const country = teamNames[team.code] ?? team.code;
  const result = [];
  // 1: Escudo (especial)
  result.push({
    number: `${team.code}1`,
    name: `Escudo — ${country}`,
    team: team.code,
    rarity: 'especial',
    isSpecial: true,
  });
  // 2: Foto del equipo
  result.push({
    number: `${team.code}2`,
    name: `Foto del Equipo — ${country}`,
    team: team.code,
    rarity: 'comun',
    isSpecial: false,
  });
  // 3-20: 18 jugadores
  team.players.forEach(([name, rarity], i) => {
    result.push({
      number: `${team.code}${i + 3}`,
      name,
      team: team.code,
      rarity,
      isSpecial: false,
    });
  });
  return result;
}

